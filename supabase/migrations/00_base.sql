-- Prague Spartans: the club's core tables, for a brand-new database.
-- Later files add security rules, member accounts and admin features.

begin;

create extension if not exists pgcrypto;

create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  player_type text not null default 'batsman',
  role text not null default 'player',
  team text,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  team1 text not null,
  team2 text not null,
  date date not null,
  time time,
  venue text,
  type text default 'friendly',
  result text not null default 'will be played',
  division text,
  url text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.practices (
  id bigint generated by default as identity primary key,
  date date not null,
  time time,
  venue text,
  type text default 'regular',
  notes text,
  first_team text,
  second_team text,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.sponsors (
  id bigint generated by default as identity primary key,
  name text not null,
  logo_url text,
  website_url text,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.committee (
  id bigint generated by default as identity primary key,
  name text not null,
  position text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.team_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  age integer,
  location text,
  specification text,
  experience text,
  status text default 'pending',
  created_at timestamptz not null default now()
);

-- Public bucket for sponsor logos (the club-photos bucket is added in 02).
insert into storage.buckets (id, name, public)
values ('sponsor-logos', 'sponsor-logos', true)
on conflict (id) do update set public = true;

commit;
